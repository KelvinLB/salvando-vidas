// Los trazos de «Sigue la señal»: un cuerpo de frente, visto por dentro y con poco detalle.
// Se dibuja la mitad izquierda y se refleja (x → 220 − x). Sin músculo expuesto ni sangre:
// solo formas suaves que dan contexto a la señal.

const W = 220
const mx = (x: number) => +(W - x).toFixed(2)

/** Refleja un trazo de la mitad izquierda a la derecha. */
export const mirror = (d: string) => d.replace(/(-?\d+(?:\.\d+)?) (-?\d+(?:\.\d+)?)/g, (_, x, y) => `${mx(+x)} ${y}`)
export const both = (d: string) => [d, mirror(d)]

type Seg = [number, number, number, number, number, number]

/** Trazo cerrado simétrico: empieza en el eje, recorre la mitad izquierda y regresa reflejado. */
function sym(start: [number, number], segs: Seg[]) {
  let d = `M${start[0]} ${start[1]}`
  const pts: [number, number][] = [start]
  for (const s of segs) {
    d += ` C${s[0]} ${s[1]} ${s[2]} ${s[3]} ${s[4]} ${s[5]}`
    pts.push([s[4], s[5]])
  }
  for (let i = segs.length - 1; i >= 0; i--) {
    const s = segs[i]
    const p = pts[i]
    d += ` C${mx(s[2])} ${s[3]} ${mx(s[0])} ${s[1]} ${mx(p[0])} ${p[1]}`
  }
  return d + ' Z'
}

